#!/usr/bin/env python3
"""Generate the agent files of each harness from one neutral source per agent.

Reads src/agents/*.md and writes one file per harness:
  claude: plugins/trobanga-skills/agents/
  pi:     plugins/trobanga-skills/pi/agents/
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = {
    "claude": Path("plugins/trobanga-skills/agents"),
    "pi": Path("plugins/trobanga-skills/pi/agents"),
}

# Each neutral tool name maps to the tool names of one harness.
TOOLS = {
    "claude": {
        "shell": ["Bash"],
        "read": ["Read"],
        "edit": ["Edit"],
        "write": ["Write"],
        "search": ["Grep"],
        "find": ["Glob"],
        "progress": ["ToolSearch", "mcp__trobanga-progress__step"],
    },
    "pi": {
        "shell": ["bash"],
        "read": ["read"],
        "edit": ["edit"],
        "write": ["write"],
        "search": ["grep"],
        "find": ["find", "ls"],
    },
}

# pi resolves only full model ids, not the Claude Code aliases.
PI_MODELS = {"sonnet": "claude-sonnet-5-5"}


def parse(text):
    head, _, body = text.removeprefix("---\n").partition("\n---\n")
    fields = {}
    for line in head.split("\n"):
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields, body


def split_list(value):
    return [item.strip() for item in value.split(",") if item.strip()]


def render(text, harness):
    fields, body = parse(text)
    names = TOOLS[harness]
    # An optional tool is left out where the harness does not have it.
    optional = [tool for tool in split_list(fields.pop("optional-tools", "")) if tool in names]
    wanted = split_list(fields["tools"]) + optional
    tools = [name for tool in wanted for name in names[tool]]
    fields["tools"] = ", ".join(tools)
    if harness == "pi":
        fields["model"] = PI_MODELS[fields["model"]]
        fields["thinking"] = fields.pop("effort")
        # A list turns off all ambient extensions, MCP included, and loads only what it names.
        # The Claude models come from the claude-bridge provider. In subagentOnlyExtensions it
        # registers too late, and the child fails with "Model not found".
        fields["extensions"] = "npm:pi-claude-bridge"
    head = "\n".join(f"{key}: {value}".rstrip() for key, value in fields.items())
    note = f"# Generated by scripts/gen_agents.py. Edit src/agents/{fields['name']}.md."
    return f"---\n{note}\n{head}\n---\n{body}"


def expected(root):
    """Return the text of each output file, by path relative to root."""
    files = {}
    for source in sorted((root / "src" / "agents").glob("*.md")):
        for harness, out in OUTPUT.items():
            files[out / source.name] = render(source.read_text(), harness)
    return files


def main(argv, root=ROOT):
    check = "--check" in argv
    files = expected(root)
    # Every .md file in an output directory is generated, so one without a source is stale.
    present = {path.relative_to(root) for out in OUTPUT.values() for path in (root / out).glob("*.md")}
    stale = sorted(path for path in files if not (root / path).exists() or (root / path).read_text() != files[path])
    orphans = sorted(present - files.keys())
    if check:
        for path in stale + orphans:
            print(f"{path}: out of date, run scripts/gen_agents.py")
        return 1 if stale or orphans else 0
    for path in stale:
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(files[path])
    for path in orphans:
        (root / path).unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
