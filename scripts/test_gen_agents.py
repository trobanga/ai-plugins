"""Tests for gen_agents.py: one neutral agent source, one output per harness."""

import pytest

import gen_agents

SOURCE = """---
name: crap-agent
description: Lower the CRAP score.
model: sonnet
effort: medium
tools: shell, read, edit, write, search, find
skills: crap-score
---

You bring the CRAP score down.
"""


def frontmatter(text):
    head, _, _ = text.partition("\n---\n")
    lines = [line for line in head.split("\n")[1:] if line and not line.startswith("#")]
    return dict(line.split(":", 1) for line in lines)


def fields(text):
    return {key: value.strip() for key, value in frontmatter(text).items()}


def test_claude_output_names_the_claude_code_tools():
    out = fields(gen_agents.render(SOURCE, "claude"))
    assert out["tools"] == "Bash, Read, Edit, Write, Grep, Glob"


def test_pi_output_names_the_pi_tools():
    out = fields(gen_agents.render(SOURCE, "pi"))
    assert out["tools"] == "bash, read, edit, write, grep, find, ls"


def test_pi_output_names_the_full_model_and_thinking_level():
    out = fields(gen_agents.render(SOURCE, "pi"))
    assert out["model"] == "claude-sonnet-5-5"
    assert out["thinking"] == "medium"
    assert "effort" not in out


def test_claude_output_keeps_the_model_alias_and_effort():
    out = fields(gen_agents.render(SOURCE, "claude"))
    assert out["model"] == "sonnet"
    assert out["effort"] == "medium"
    assert "thinking" not in out


def test_pi_output_loads_no_ambient_extensions():
    out = fields(gen_agents.render(SOURCE, "pi"))
    assert out["extensions"] == ""


def test_claude_output_has_no_extensions_field():
    assert "extensions" not in fields(gen_agents.render(SOURCE, "claude"))


WITH_PROGRESS = SOURCE.replace("skills:", "optional-tools: progress\nskills:")


def test_claude_output_adds_the_progress_tools():
    out = fields(gen_agents.render(WITH_PROGRESS, "claude"))
    assert out["tools"].endswith("Glob, ToolSearch, mcp__trobanga-progress__step")
    assert "optional-tools" not in out


def test_pi_output_drops_tools_that_pi_does_not_have():
    out = fields(gen_agents.render(WITH_PROGRESS, "pi"))
    assert out["tools"] == "bash, read, edit, write, grep, find, ls"
    assert "optional-tools" not in out


@pytest.mark.parametrize("harness", ["claude", "pi"])
def test_output_says_where_to_edit_and_keeps_the_rest(harness):
    text = gen_agents.render(SOURCE, harness)
    out = fields(text)
    assert "# Generated by scripts/gen_agents.py. Edit src/agents/crap-agent.md." in text
    assert out["name"] == "crap-agent"
    assert out["description"] == "Lower the CRAP score."
    assert out["skills"] == "crap-score"
    assert text.endswith("\n---\n\nYou bring the CRAP score down.\n")


CLAUDE_OUT = "plugins/trobanga-skills/agents/crap-agent.md"
PI_OUT = "plugins/trobanga-skills/pi/agents/crap-agent.md"


@pytest.fixture
def root(tmp_path):
    (tmp_path / "src" / "agents").mkdir(parents=True)
    (tmp_path / "src" / "agents" / "crap-agent.md").write_text(SOURCE)
    return tmp_path


def test_main_writes_one_file_per_harness(root):
    assert gen_agents.main([], root) == 0
    assert (root / CLAUDE_OUT).read_text() == gen_agents.render(SOURCE, "claude")
    assert (root / PI_OUT).read_text() == gen_agents.render(SOURCE, "pi")


def test_check_passes_when_the_outputs_are_current(root):
    gen_agents.main([], root)
    assert gen_agents.main(["--check"], root) == 0


def test_check_fails_and_names_a_stale_output(root, capsys):
    gen_agents.main([], root)
    (root / PI_OUT).write_text("edited by hand\n")
    assert gen_agents.main(["--check"], root) == 1
    assert PI_OUT in capsys.readouterr().out
    assert (root / PI_OUT).read_text() == "edited by hand\n"


def test_check_fails_on_a_missing_output(root):
    assert gen_agents.main(["--check"], root) == 1
    assert not (root / CLAUDE_OUT).exists()


def test_an_output_without_a_source_is_removed_or_reported(root, capsys):
    gen_agents.main([], root)
    orphan = root / "plugins/trobanga-skills/pi/agents/old-agent.md"
    orphan.write_text("old\n")
    assert gen_agents.main(["--check"], root) == 1
    assert "pi/agents/old-agent.md" in capsys.readouterr().out
    assert gen_agents.main([], root) == 0
    assert not orphan.exists()
